	static CurrencyCountryMap() {
		var classified = Map.Keys.Concat(CodeWithNoCountry.Keys).ToHashSet();
		var missing = Enum.GetValues<ECurrencyISO>().Where(currency => !classified.Contains(currency)).ToArray();

		if (missing.Length > 0) {
			throw new InvalidOperationException($"CurrencyCountryMap is missing mappings for: {string.Join(", ", missing)}");
		}
	}

	public static string GetCountryCode(ECurrencyISO currency) {
		if (Map.TryGetValue(currency, out var countryCode)) {
			return countryCode;
		}

		if (CodeWithNoCountry.ContainsKey(currency)) {
			throw new NotSupportedException($"Currency '{currency}' does not map to a single country.");
		}

		throw new NotSupportedException($"Currency '{currency}' is not mapped.");
	}

